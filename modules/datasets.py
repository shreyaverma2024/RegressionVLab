def load_dataset(dataset_name):
    """Return all curated rows as X (n, 1), y (n,) without runtime downloads.

    Synthetic data remains generated by the app's existing generate_dataset.
    No rows are sampled, sorted, or modified here.
    """
    if dataset_name not in DATASETS or dataset_name == "Synthetic":
        raise ValueError(f"Not a curated dataset: {dataset_name}")

    if dataset_name == "Diabetes BMI vs Disease Progression":
        diabetes = load_diabetes()
        bmi_index = diabetes.feature_names.index("bmi")
        return diabetes.data[:, [bmi_index]], diabetes.target.copy()

    dataset_info = DATASETS[dataset_name]
    frame = pd.read_csv(DATA_DIR / dataset_info["filename"])
    X = frame[[dataset_info["feature"]]].to_numpy(dtype=float)
    y = frame[dataset_info["target"]].to_numpy(dtype=float)
    return X, y
